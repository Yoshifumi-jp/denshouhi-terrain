def select_zone(pref_code, lat, lon, muni_code=None):
    """
    緯度経度や市区町村コードから平面直角座標系の系番号（1〜19）を判定する。
    """
    if pref_code not in PREFECTURES:
        raise ValueError(f"県コードが正しくありません: {pref_code}")
    
    if pref_code == "01":
        if not muni_code or not isinstance(muni_code, str) or not muni_code.startswith("01") or len(muni_code) != 5:
            raise ValueError(f"北海道の碑は市区町村コード（01で始まる5桁）が必要です: {muni_code}")
        if muni_code in HOKKAIDO_ZONE11_CODES:
            return 11
        if muni_code in HOKKAIDO_ZONE13_CODES:
            return 13
        return 12
        
    if pref_code == "13":
        if lat < 28.0:
            if lon < 140.5:
                return 18
            if lon >= 143.0:
                return 19
            return 14
        return 9
        
    if pref_code == "47":
        if lon < 126.0:
            return 16
        if lon >= 130.0:
            return 17
        return 15
        
    if pref_code == "46":
        # 告示の I系の区域「北緯32度・27度、東経128度18分・130度で囲む区域内の島（奄美群島は東経130度13分まで）」を緯度経度で判定している。
        # 奄美群島は北緯29度より南。九州本土には東経130度より西の陸地はない（推測を含む。最西端の野間岬付近は東経130.1度台）
        if 27.0 <= lat <= 32.0 and lon >= 128.3 and (lon <= 130.0 or (lat < 29.0 and lon <= 130.0 + 13/60)):
            return 1
        return 2

    return PREF_ZONE[pref_code]

def select_epsg(pref_code, lat, lon, muni_code=None):
    """
    緯度経度や市区町村コードから平面直角座標系のEPSGコード（6669〜6687）を判定する。
    """
    zone = select_zone(pref_code, lat, lon, muni_code)
    return JPC_EPSG[zone]


